export type AttachmentRequest = {
  fileName: unknown;
  mimeType: unknown;
  sizeBytes: unknown;
};

export type AttachmentPolicy = {
  maxAttachmentMb: number;
  allowedMimeTypes: string[];
};

// Known extensions must agree with the declared content type. Without this
// guard, a filename such as "payload.pdf" can pass an image/* policy because
// extension and MIME rules are currently alternatives.
// Reject executable/script-capable suffixes even when a client lies about MIME type
// or appends an allowed-looking extension. Support attachments are untrusted content.
const BLOCKED_ACTIVE_CONTENT_EXTENSION = /\.(?:exe|dll|bat|cmd|com|msi|msp|scr|ps1|psm1|sh|bash|zsh|vbs|vbe|js|mjs|cjs|jar|html?|xhtml|svg|php|phtml|asp|aspx|jsp|jspx|wsf|hta)(?:\.|$)/i;

const KNOWN_EXTENSION_MIME_TYPES: Record<string, readonly string[]> = {
  ".pdf": ["application/pdf"],
  ".png": ["image/png"],
  ".jpg": ["image/jpeg"],
  ".jpeg": ["image/jpeg"],
  ".gif": ["image/gif"],
  ".webp": ["image/webp"],
  ".txt": ["text/plain"],
  ".csv": ["text/csv", "application/csv"],
  ".json": ["application/json"],
};

/**
 * Validate presigned-upload metadata before using values in MIME/extension
 * checks. Malformed input is rejected without throwing from string methods.
 */
export function isAllowedAttachmentRequest(
  request: AttachmentRequest,
  policy: AttachmentPolicy,
): boolean {
  const { fileName, mimeType, sizeBytes } = request;
  // Fail closed when configuration is corrupt or incomplete. In particular,
  // comparisons against NaN are always false and would otherwise bypass the
  // maximum-size check.
  if (
    !Number.isFinite(policy?.maxAttachmentMb) ||
    policy.maxAttachmentMb <= 0 ||
    !Array.isArray(policy.allowedMimeTypes) ||
    policy.allowedMimeTypes.length === 0 ||
    policy.allowedMimeTypes.some(rule => typeof rule !== "string" || rule.trim().length === 0)
  ) {
    return false;
  }

  if (
    typeof fileName !== "string" ||
    typeof mimeType !== "string" ||
    fileName.trim().length === 0 ||
    /[\u0000-\u001f\u007f]/.test(fileName) ||
    mimeType.trim().length === 0 ||
    // Require a syntactically valid bare MIME type before wildcard matching;
    // values such as "image/" must not pass an "image/*" policy.
    !/^[a-zA-Z0-9][a-zA-Z0-9._+-]*\/[a-zA-Z0-9][a-zA-Z0-9._+-]*$/.test(mimeType) ||
    typeof sizeBytes !== "number" ||
    !Number.isSafeInteger(sizeBytes) ||
    sizeBytes < 1 ||
    sizeBytes > policy.maxAttachmentMb * 1_000_000
  ) {
    return false;
  }

  // Normalize filename suffixes before extension checks. Trailing dots/spaces are
  // ignored by some filesystems and can otherwise disguise a known extension.
  const normalizedName = fileName.trim().toLowerCase().replace(/[. ]+$/, "");
  const normalizedMimeType = mimeType.toLowerCase();
  if (BLOCKED_ACTIVE_CONTENT_EXTENSION.test(normalizedName)) return false;
  const knownExtension = Object.keys(KNOWN_EXTENSION_MIME_TYPES).find(extension =>
    normalizedName.endsWith(extension),
  );
  if (
    knownExtension &&
    normalizedMimeType !== "application/octet-stream" &&
    !KNOWN_EXTENSION_MIME_TYPES[knownExtension].includes(normalizedMimeType)
  ) {
    return false;
  }

  return policy.allowedMimeTypes.some(rule => {
    const normalizedRule = rule.trim().toLowerCase();
    return (
      normalizedRule === normalizedMimeType ||
      (normalizedRule.endsWith("/*") && normalizedMimeType.startsWith(normalizedRule.slice(0, -1))) ||
      (normalizedRule.startsWith(".") && normalizedName.endsWith(normalizedRule))
    );
  });
}

/** Accept only keys generated by the support attachment presign route. */
export function isValidSupportAttachmentStorageKey(value: unknown): value is string {
  return typeof value === "string" && /^support\/(?:\d+-[a-f0-9]{48}-[a-zA-Z0-9._-]{1,120}|\d+\/[a-f0-9]{48}-[a-zA-Z0-9._-]{1,120})$/.test(value);
}
