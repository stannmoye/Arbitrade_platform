CREATE TABLE IF NOT EXISTS `opportunity_delivery_diagnostic_events` (
  `id` int NOT NULL AUTO_INCREMENT,
  `opportunityId` int NOT NULL,
  `customerId` int NOT NULL,
  `popupEventId` int NULL,
  `eventType` varchar(40) NOT NULL,
  `eventAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `workerId` varchar(128) NULL,
  `retryAttempt` int NULL,
  `retryAt` timestamp NULL,
  `errorCode` varchar(80) NULL,
  `failureCategory` varchar(48) NULL,
  `diagnosticMessage` varchar(240) NULL,
  `metadataJson` text NULL,
  `idempotencyKey` varchar(200) NOT NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `opportunity_delivery_diag_idempotency_uq` (`idempotencyKey`),
  KEY `opportunity_delivery_diag_offer_idx` (`opportunityId`,`id`),
  KEY `opportunity_delivery_diag_customer_offer_idx` (`customerId`,`opportunityId`,`id`),
  KEY `opportunity_delivery_diag_customer_time_idx` (`customerId`,`eventAt`,`id`),
  KEY `opportunity_delivery_diag_event_time_idx` (`eventAt`,`id`),
  KEY `opportunity_delivery_diag_type_time_idx` (`eventType`,`eventAt`,`id`),
  KEY `opportunity_delivery_diag_worker_time_idx` (`workerId`,`eventAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
