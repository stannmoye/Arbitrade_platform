-- Evidence-backed settlement recovery proposals. Creating a case never moves funds.
CREATE TABLE `trade_settlement_recovery_cases` (
  `id` int NOT NULL AUTO_INCREMENT,
  `tradeId` int NOT NULL,
  `userId` int NOT NULL,
  `currency` varchar(12) NOT NULL,
  `settlementReference` varchar(160) DEFAULT NULL,
  `correctionMode` enum('ledger_only','wallet_and_ledger') NOT NULL,
  `amountMinor` bigint NOT NULL,
  `evidenceReference` varchar(160) NOT NULL,
  `evidenceSummary` text NOT NULL,
  `reason` text NOT NULL,
  `idempotencyKey` varchar(180) NOT NULL,
  `status` enum('pending_approval','approved','rejected','resolved') NOT NULL DEFAULT 'pending_approval',
  `proposedBy` int NOT NULL,
  `approvedBy` int DEFAULT NULL,
  `reviewNote` text,
  `reviewedAt` timestamp NULL DEFAULT NULL,
  `resolvedBy` int DEFAULT NULL,
  `resolvedAt` timestamp NULL DEFAULT NULL,
  `recoveryLedgerReference` varchar(80) DEFAULT NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `trade_settlement_recovery_idempotency_unique` (`idempotencyKey`),
  UNIQUE KEY `trade_settlement_recovery_ledger_reference_unique` (`recoveryLedgerReference`),
  KEY `trade_settlement_recovery_status_created_idx` (`status`, `createdAt`, `id`),
  KEY `trade_settlement_recovery_trade_idx` (`tradeId`, `id`)
);
